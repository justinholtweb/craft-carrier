"""Carrier's icon, and the add-on icons built from it.

    python3 icon-gen.py            # writes every icon into its repo
    python3 icon-gen.py <outdir>   # writes them all under <outdir> instead, for previewing

Carrier follows the family icon standard: 100x100 viewBox, a flat accent tile with rx=22.44, and
a #FEFEFE glyph made only of filled geometry, so icon-mask.svg is the same glyph with the tile
removed. The glyph is a parcel seen from above, its three faces split by a gutter.

Each add-on icon is Carrier's icon with a triangle in the bottom-left corner, in the add-on's
colour, carrying a small generic mark — a truck, an envelope, a pallet, a pin. Erpy's add-ons
carry vendor logos; these deliberately do not. A carrier's logo is its trademark, and a mark that
only says "this is the parcel one" or "this is the freight one" identifies the add-on without
borrowing anybody's brand. The parcel's left face clears the triangle's hypotenuse by ~4.6 units,
so the two never touch.
"""
import os, sys

TILE = '#3B4CCA'
GLYPH = '#FEFEFE'
R = 22.44
LEG = 50

PARCEL = 'M50 22L77 35.5L50 49L23 35.5ZM23 40L48 52.5L48 79L23 66.5ZM52 52.5L77 40L77 66.5L52 79Z'

# Marks drawn in a 16x16 box; placed centred on the triangle's incircle, which keeps them inside
# both the hypotenuse and the tile's rounded corner.
MARKS = {
    'truck': [('M0 3H10V12H0Z', False), ('M10.6 5.5H13L16 8.6V12H10.6Z', False),
              ('M1.5 13.2a2 2 0 1 0 4 0a2 2 0 1 0 -4 0Z', False), ('M10.5 13.2a2 2 0 1 0 4 0a2 2 0 1 0 -4 0Z', False)],
    'plane': [('M8 0C8.9 0 9.3 1 9.3 2.2V6L16 9.6V11.4L9.3 9.4V13L11.2 14.4V16L8 15L4.8 16V14.4L6.7 13V9.4L0 11.4V9.6L6.7 6V2.2C6.7 1 7.1 0 8 0Z', False)],
    'envelope': [('M0 2.5H16V13.5H0ZM1.6 4.4V5.9L8 10.4L14.4 5.9V4.4L8 8.9Z', True)],
    'pallet': [('M1 1.5H7.4V8.4H1Z', False), ('M8.6 1.5H15V8.4H8.6Z', False), ('M0 9.6H16V11.6H0Z', False),
               ('M0.6 12.6H3.6V15H0.6Z', False), ('M6.5 12.6H9.5V15H6.5Z', False), ('M12.4 12.6H15.4V15H12.4Z', False)],
    'parcel': [('M8 0.5L15.5 4.3L8 8.1L0.5 4.3Z', False), ('M0.5 5.6L7.3 9V15.6L0.5 12.2Z', False), ('M8.7 9L15.5 5.6V12.2L8.7 15.6Z', False)],
    'pin': [('M8 0A6 6 0 0 1 14 6C14 10 8 16 8 16C8 16 2 10 2 6A6 6 0 0 1 8 0ZM5.6 6a2.4 2.4 0 1 0 4.8 0a2.4 2.4 0 1 0 -4.8 0Z', True)],
    'lockers': [(''.join(f'M{x} {y}H{x + 4.4}V{y + 4.4}H{x}Z' for x in (1, 5.8, 10.6) for y in (1, 5.8, 10.6)), False)],
    'horn': [('M0.5 9a5.5 5.5 0 1 0 11 0a5.5 5.5 0 1 0 -11 0ZM3 9a3 3 0 1 0 6 0a3 3 0 1 0 -6 0Z', True),
             ('M9.5 4.2H13V6.6H9.5Z', False), ('M12.4 1.6L16 0V10.8L12.4 9.2Z', False)],
}

ADDONS = {
    'ups':     {'colour': '#5B3A1F', 'mark': 'truck',    'markColour': GLYPH},
    'fedex':   {'colour': '#4D148C', 'mark': 'plane',    'markColour': GLYPH},
    'usps':    {'colour': '#14204A', 'mark': 'envelope', 'markColour': GLYPH},
    'freight': {'colour': '#B4531A', 'mark': 'pallet',   'markColour': GLYPH},
    'dpd':     {'colour': '#B0173A', 'mark': 'parcel',   'markColour': GLYPH},
    'gls':     {'colour': '#F2B705', 'mark': 'pin',      'markColour': '#1F2E8F'},
    'boxnow':  {'colour': '#3E9B4F', 'mark': 'lockers',  'markColour': GLYPH},
    'posts':   {'colour': '#E09A00', 'mark': 'horn',     'markColour': GLYPH},
}


def mark_paths(name, colour):
    # Incircle of the (0,50)-(0,100)-(50,100) triangle sits at (14.64, 85.36), radius 14.64.
    scale, cx, cy = 1.05, 14.9, 85.1
    tx, ty = cx - 8 * scale, cy - 8 * scale
    out = []

    for d, evenodd in MARKS[name]:
        rule = ' fill-rule="evenodd"' if evenodd else ''
        out.append(f'        <path fill="{colour}"{rule} transform="translate({tx:.2f} {ty:.2f}) scale({scale})" d="{d}"/>')

    return '\n'.join(out)


def gateway_svg():
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
    <!-- Carrier: a parcel seen from above, three faces split by a gutter. Family standard: flat
         tile, rx 22.44, filled #FEFEFE glyph, no strokes. Generated by promos/icon-gen.py. -->
    <rect x="0" y="0" width="100" height="100" rx="{R}" fill="{TILE}"/>
    <path fill="{GLYPH}" d="{PARCEL}"/>
</svg>
'''


def mask_svg():
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
    <path d="{PARCEL}"/>
</svg>
'''


def watermark_svg():
    # The glyph without its tile, cropped so the faces run off the edge: a tile at watermark
    # scale reads as a hard-edged box behind every slide.
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="30 30 50 50">
    <path fill="{GLYPH}" d="{PARCEL}"/>
</svg>
'''


def addon_svg(key):
    a = ADDONS[key]
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
    <!-- Carrier for {key}: Carrier's parcel, plus the add-on's corner. A generic mark, never the
         carrier's logo. Generated by craft-carrier/promos/icon-gen.py. -->
    <defs><clipPath id="tile-{key}"><rect width="100" height="100" rx="{R}"/></clipPath></defs>
    <rect x="0" y="0" width="100" height="100" rx="{R}" fill="{TILE}"/>
    <path fill="{GLYPH}" d="{PARCEL}"/>
    <path clip-path="url(#tile-{key})" fill="{a['colour']}" d="M0 {100 - LEG}L{LEG} 100H0Z"/>
{mark_paths(a['mark'], a['markColour'])}
</svg>
'''


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as fh:
        fh.write(content)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.dirname(here)
    sites = os.path.dirname(repo)
    preview = sys.argv[1] if len(sys.argv) > 1 else None

    def target(*parts):
        return os.path.join(preview, *parts[-2:]) if preview else os.path.join(*parts)

    write(target(repo, 'src', 'icon.svg'), gateway_svg())
    write(target(repo, 'src', 'icon-mask.svg'), mask_svg())
    write(target(here, 'assets', 'icon.svg'), gateway_svg())
    write(target(here, 'assets', 'watermark.svg'), watermark_svg())

    for key in ADDONS:
        svg = addon_svg(key)
        write(target(here, 'assets', 'addons', f'{key}.svg'), svg)
        write(target(sites, f'craft-carrier-{key}', 'src', 'icon.svg'), svg)

    print('wrote gateway + %d add-on icons' % len(ADDONS))


if __name__ == '__main__':
    main()
